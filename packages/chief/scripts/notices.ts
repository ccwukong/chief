/**
 * Third-party notices, generated at build time into `dist/` — never committed (task 15.18).
 *
 * The list has always come from `package-lock.json`, so nobody maintained it by hand; what was painful
 * was that it was a 1,200-line tracked file, rewritten in every diff whenever a dependency moved. So it
 * is no longer in the repository at all: `npm run build` writes it beside the bundle and the desktop
 * build copies it into the app, because MIT, ISC and BSD require their copyright notice to be
 * reproduced in the copies that are distributed (and only those copies).
 *
 * Nothing here is a source of truth that can go stale: each build regenerates it from the lockfile in
 * the tree it is building.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
/** The packages this workspace ships: everything else in the lockfile is a build tool. */
const OWN = new Set(["", "packages/chief", "packages/web", "packages/desktop"]);

export interface Notices {
  packages: number;
  texts: number;
  file: string;
}

/** Write `THIRD-PARTY-NOTICES.md` into `outDir` (usually `dist/`) and return what it holds. */
export function writeNotices(outDir: string): Notices {
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));

  // Every runtime package, from the lockfile, so a dependency added or removed needs no edit anywhere.
  const found = new Map<string, { name: string; version: string; license: string }>();
  for (const [path, meta] of Object.entries<any>(lock.packages ?? {})) {
    if (OWN.has(path) || meta.dev || meta.link || !path.startsWith("node_modules/")) continue;
    const name = meta.name ?? path.slice("node_modules/".length).replace(/^.*\/node_modules\//, "");
    const key = `${name}@${meta.version}`;
    if (found.has(key)) continue;
    let license = meta.license ?? "unknown";
    try { license = JSON.parse(readFileSync(join(root, path, "package.json"), "utf8")).license ?? license; } catch { /* the lockfile's value stands */ }
    found.set(key, { name, version: meta.version, license: String(license) });
  }
  const rows = [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

  // Each distinct license file once, verbatim, with the packages that ship it.
  const texts = new Map<string, { text: string; license: string; packages: string[] }>();
  for (const p of rows) {
    const dir = join(root, "node_modules", p.name);
    if (!existsSync(dir)) continue;
    const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f));
    if (!file) continue;
    const text = readFileSync(join(dir, file), "utf8").trim();
    if (!text) continue;
    const key = createHash("sha1").update(text).digest("hex");
    if (!texts.has(key)) texts.set(key, { text, license: p.license, packages: [] });
    texts.get(key)!.packages.push(`${p.name}@${p.version}`);
  }
  const groups = [...texts.values()].sort((a, b) => a.license.localeCompare(b.license) || b.packages.length - a.packages.length);
  const counts = rows.reduce<Record<string, number>>((m, r) => ({ ...m, [r.license]: (m[r.license] ?? 0) + 1 }), {});

  const lines = [
    "# Third-party notices",
    "",
    "chief bundles third-party software in `chief.mjs` and in the built web UI. This file lists every runtime",
    "package and reproduces, verbatim, every license text involved: MIT, ISC and BSD require the copyright",
    "notice to travel with the text. It is generated by every build from `package-lock.json` and is not part",
    "of the source tree, so it always describes the copy it sits beside.",
    "",
    "chief itself is licensed under the Apache License 2.0 (see `LICENSE`). Nothing here changes the terms of",
    "any third-party license, and those terms win over chief's where they differ.",
    "",
    `**${rows.length} packages** — ` + Object.entries(counts).map(([l, n]) => `${n} ${l}`).join(", ") + ".",
    "",
    "Build-only tools (esbuild, TypeScript, ESLint, Vite, Playwright) are not redistributed with chief and are",
    "not listed. The desktop application adds Electron, Chromium and Node, which carry their own notices.",
    "",
    "| Package | Version | License |",
    "|---|---|---|",
    ...rows.map((r) => `| \`${r.name}\` | ${r.version} | ${r.license} |`),
    "",
    "## License texts",
    "",
  ];
  for (const [i, g] of groups.entries()) {
    lines.push(`### ${i + 1}. ${g.license} — ${g.packages.length === 1 ? "1 package" : `${g.packages.length} packages`}`, "");
    lines.push("Used by: " + g.packages.map((p) => `\`${p}\``).join(", "), "");
    lines.push("```text", g.text.replace(/```/g, "'''"), "```", "");
  }
  const withText = new Set(groups.flatMap((g) => g.packages.map((p) => p.replace(/@[^@]+$/, ""))));
  const withoutText = rows.filter((r) => !withText.has(r.name));
  if (withoutText.length) {
    lines.push("## Packages without a license file", "", "These ship no license file to reproduce; their license field is:", "");
    for (const r of withoutText) lines.push(`- \`${r.name}@${r.version}\` — ${r.license}`);
    lines.push("");
  }

  mkdirSync(outDir, { recursive: true });
  const file = join(outDir, "THIRD-PARTY-NOTICES.md");
  writeFileSync(file, lines.join("\n") + "\n");
  return { packages: rows.length, texts: groups.length, file };
}
