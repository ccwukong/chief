/**
 * Build the `chief` server: the CLI, engine and server bundled into one Node module, with the
 * built web UI embedded, plus the SQL migrations beside it. Run `npm run build` from the repo root
 * (it builds the web UI first).
 *
 * The build produces `dist/chief.mjs`, run with `node dist/chief.mjs`; Node is therefore a
 * requirement of the server (>= 22.18, for TypeScript type stripping if the source is run
 * directly). A self-contained executable needs the SEA (single executable application) step, or
 * a Node bundled into the desktop app: those are the ways to remove that requirement
 * (dev plan §12, B.11).
 */
import { build } from "esbuild";
import { chmodSync, copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeNotices } from "./notices.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const webDist = join(root, "packages/web/dist");
const migrationsDir = join(root, "packages/chief/src/store/migrations");
const generated = join(root, "packages/chief/src/server/web-assets.generated.ts");
const outfile = resolve(process.argv[2] ?? join(root, "dist/chief.mjs"));

if (!existsSync(join(webDist, "index.html"))) {
  console.error("packages/web/dist is missing. Run `npm run build:web` first (or `npm run build` from the repo root).");
  process.exit(1);
}

const MIME: Record<string, string> = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml", ".json": "application/json", ".png": "image/png", ".ico": "image/x-icon", ".woff2": "font/woff2",
};
const files: Record<string, { type: string; b64: string }> = {};
const walk = (dir: string) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (extname(p) !== ".map") files["/" + relative(webDist, p).split("\\").join("/")] = { type: MIME[extname(p)] ?? "application/octet-stream", b64: readFileSync(p).toString("base64") };
  }
};
walk(webDist);

writeFileSync(generated, `// Generated by scripts/build.ts. Do not edit or commit.
const files: Record<string, { type: string; b64: string }> = ${JSON.stringify(files)};
const cache = new Map<string, Uint8Array>();
export const assets = {
  get(path: string) {
    const f = files[path];
    if (!f) return null;
    if (!cache.has(path)) cache.set(path, new Uint8Array(Buffer.from(f.b64, "base64")));
    return { body: cache.get(path)!, type: f.type };
  },
};
`);

try {
  mkdirSync(dirname(outfile), { recursive: true });
  await build({
    entryPoints: [join(root, "packages/chief/src/cli.ts")],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    outfile,
    minify: true,
    // esbuild keeps the entry file's own `#!/usr/bin/env node` line, so no banner is added here.
  });
  chmodSync(outfile, 0o755);
  // A bundled dependency (yaml, hono) is CommonJS and calls `require` for Node built-ins. An ES
  // module has no `require`, so one is created and put in scope just after the shebang line.
  {
    const code = readFileSync(outfile, "utf8");
    const shim = 'import{createRequire as __chiefCreateRequire}from"node:module";const require=__chiefCreateRequire(import.meta.url);';
    const eol = code.indexOf("\n");
    writeFileSync(outfile, code.startsWith("#!") ? code.slice(0, eol + 1) + shim + code.slice(eol + 1) : `#!/usr/bin/env node\n${shim}\n${code}`);
  }
  // The migrations are read from disk at startup; beside the bundle they live in migrations/.
  const outMigrations = join(dirname(outfile), "migrations");
  mkdirSync(outMigrations, { recursive: true });
  let sql = 0;
  for (const name of readdirSync(migrationsDir)) {
    if (!name.endsWith(".sql")) continue;
    copyFileSync(join(migrationsDir, name), join(outMigrations, name));
    sql++;
  }
  const size = statSync(outfile).size;
  // What a distributed copy must carry (task 15.18): chief's own LICENSE, and the third-party notices
  // MIT/ISC/BSD require to travel with the code — generated here from the lockfile, not committed.
  const notices = writeNotices(dirname(outfile));
  copyFileSync(join(root, "LICENSE"), join(dirname(outfile), "LICENSE"));
  console.log(`built ${outfile} (${(size / 1024 / 1024).toFixed(1)} MB, ${Object.keys(files).length} web files embedded, ${sql} migrations beside it, ${notices.packages} third-party notices; state in ~/.chief)`);
  console.log(`run it with: node ${relative(process.cwd(), outfile) || outfile} --help`);
} finally {
  // Left in place, the dev server would serve these stale assets instead of packages/web/dist.
  rmSync(generated, { force: true });
}
